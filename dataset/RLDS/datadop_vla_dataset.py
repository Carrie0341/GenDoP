# -*- coding: utf-8 -*-
"""
Step 2: DataDoP Dataset TFDS Builder

This script defines a GeneratorBasedBuilder for converting DataDoP intermediate .npy files
to OpenVLA/RLDS standard TFRecord format.

Author: Gemini (Adapted from ET-VLA conversion)
Date: 2025-12-03

Usage:
    # Build test dataset
    tfds build --config=datadop_vla_test --data_dir=./DATA/TFDS --manual_dir=./DATA/datadop-npy-test/splits
    
    # Build full dataset
    tfds build --config=datadop_vla --data_dir=./DATA/TFDS --manual_dir=./DATA/datadop-npy/splits
"""

import os
from typing import Iterator, Tuple, Any
import glob
import numpy as np
import tensorflow_datasets as tfds


class DataDoPVLA(tfds.core.GeneratorBasedBuilder):
    """DataDoP dataset builder for OpenVLA/RLDS format."""

    VERSION = tfds.core.Version('1.0.0')
    RELEASE_NOTES = {
        '1.0.0': 'Initial release with 7D action space and multi-level captions.',
    }

    MANUAL_DOWNLOAD_INSTRUCTIONS = """
    This dataset is built from local .npy files generated by the
    `generate_datadop_npy.py` script. Please run that script first and
    provide the path to the output directory via the `--manual_dir` flag.
    """

    # BuilderConfig for different dataset variants
    BUILDER_CONFIGS = [
        tfds.core.BuilderConfig(
            name="datadop_vla",
            description="Full DataDoP dataset with train and val splits."
        ),
        tfds.core.BuilderConfig(
            name="datadop_vla_test",
            description="Small-scale test dataset for validation."
        ),
    ]

    def _info(self) -> tfds.core.DatasetInfo:
        """Define dataset metadata and feature structure."""
        return self.dataset_info_from_configs(
            features=tfds.features.FeaturesDict({
                'steps': tfds.features.Dataset({
                    'observation': tfds.features.FeaturesDict({
                        'image': tfds.features.Image(
                            shape=(224, 224, 3),
                            dtype=np.uint8,
                            encoding_format='jpeg',
                            doc='RGB observation from first frame.',
                        ),
                        'state': tfds.features.Tensor(
                            shape=(7,),  # pos (3) + quat (4)
                            dtype=np.float32,
                            doc='Camera absolute pose [x, y, z, qx, qy, qz, qw].',
                        )
                    }),
                    'action': tfds.features.Tensor(
                        shape=(7,),  # delta_pos (3) + delta_euler (3) + placeholder (1)
                        dtype=np.float32,
                        doc='Relative camera action [dx, dy, dz, d_roll, d_pitch, d_yaw, placeholder].',
                    ),
                    'discount': tfds.features.Scalar(
                        dtype=np.float32,
                        doc='Discount factor, always 1.0 for imitation learning.'
                    ),
                    'reward': tfds.features.Scalar(
                        dtype=np.float32,
                        doc='Reward, 1.0 on the last step of a successful demo.'
                    ),
                    'is_first': tfds.features.Scalar(
                        dtype=np.bool_,
                        doc='True on first step.'
                    ),
                    'is_last': tfds.features.Scalar(
                        dtype=np.bool_,
                        doc='True on last step.'
                    ),
                    'is_terminal': tfds.features.Scalar(
                        dtype=np.bool_,
                        doc='True on terminal step.'
                    ),
                    'language_instruction': tfds.features.Text(
                        doc='Formatted camera movement instruction.'
                    ),
                }),
                'episode_metadata': tfds.features.FeaturesDict({
                    'file_path': tfds.features.Text(
                        doc='Path to the original .npy file.'
                    ),
                    'movement_caption': tfds.features.Text(
                        doc='Movement caption from DataDoP.'
                    ),
                    'detailed_caption': tfds.features.Text(
                        doc='Detailed interaction caption from DataDoP.'
                    ),
                    'concise_caption': tfds.features.Text(
                        doc='Concise interaction caption from DataDoP.'
                    ),
                }),
            })
        )

    def _split_generators(self, dl_manager: tfds.download.DownloadManager):
        """Define dataset train/val/test splits."""
        data_dir = dl_manager.manual_dir
        
        splits = {}
        config = self.builder_config.name
        print(f"!!data_dir: {data_dir}")
        
        if config == 'datadop_vla':
            # Full dataset with train/val/test
            if os.path.isdir(os.path.join(data_dir, 'train')):
                splits['train'] = self._generate_examples(os.path.join(data_dir, 'train'))
            if os.path.isdir(os.path.join(data_dir, 'val')):
                splits['val'] = self._generate_examples(os.path.join(data_dir, 'val'))
            if os.path.isdir(os.path.join(data_dir, 'test')):
                splits['test'] = self._generate_examples(os.path.join(data_dir, 'test'))
        elif config == 'datadop_vla_test':
            # Test dataset with train/val/test
            if os.path.isdir(os.path.join(data_dir, 'train')):
                splits['train'] = self._generate_examples(os.path.join(data_dir, 'train'))
            if os.path.isdir(os.path.join(data_dir, 'val')):
                splits['val'] = self._generate_examples(os.path.join(data_dir, 'val'))
            if os.path.isdir(os.path.join(data_dir, 'test')):
                splits['test'] = self._generate_examples(os.path.join(data_dir, 'test'))

        return splits

    def _generate_examples(self, path: str) -> Iterator[Tuple[str, Any]]:
        """Generate examples for each split."""
        episode_paths = glob.glob(os.path.join(path, '*.npy'))
        
        for episode_path in episode_paths:
            unique_key = os.path.basename(episode_path)
            
            try:
                episode_data = np.load(episode_path, allow_pickle=True)
                if len(episode_data) == 0:
                    continue
            except (IOError, ValueError) as e:
                print(f"Warning: Cannot load or empty file: {episode_path}, error: {e}")
                continue

            episode_steps = []
            
            # Extract caption data from first step
            caption_data = episode_data[0].get('caption_data', {})
            movement_caption = caption_data.get('Movement', '')
            detailed_caption = caption_data.get('Detailed Interaction', '')
            concise_caption = caption_data.get('Concise Interaction', '')
            
            for i, step in enumerate(episode_data):
                episode_steps.append({
                    'observation': {
                        'image': step['image'],
                        'state': step['state'],
                    },
                    'action': step['action'],
                    'discount': 1.0,
                    'reward': float(i == (len(episode_data) - 1)),
                    'is_first': i == 0,
                    'is_last': i == (len(episode_data) - 1),
                    'is_terminal': i == (len(episode_data) - 1),
                    'language_instruction': step['language_instruction'],
                })

            # Yield the full sample
            yield unique_key, {
                'steps': episode_steps,
                'episode_metadata': {
                    'file_path': episode_path,
                    'movement_caption': movement_caption,
                    'detailed_caption': detailed_caption,
                    'concise_caption': concise_caption,
                }
            }
